/**
 * Injects Firebase config from .env.local into public/firebase-messaging-sw.js
 * Run before dev/build so the service worker has the correct config.
 */
import { readFileSync, writeFileSync, existsSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const envPath = join(root, ".env.local");
const envExample = join(root, ".env.example");

function loadEnv() {
  const paths = [envPath, join(root, ".env"), join(root, ".env.production")];
  for (const p of paths) {
    if (!existsSync(p)) continue;
    const content = readFileSync(p, "utf8");
    for (const line of content.split("\n")) {
      const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
      if (m) process.env[m[1]] = m[2].replace(/^["']|["']$/g, "").trim();
    }
  }
}

loadEnv();

const config = {
  apiKey: process.env.NEXT_PUBLIC_FIREBASE_API_KEY || "",
  authDomain: process.env.NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN || "",
  projectId: process.env.NEXT_PUBLIC_FIREBASE_PROJECT_ID || "",
  storageBucket: process.env.NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET || "",
  messagingSenderId: process.env.NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID || "",
  appId: process.env.NEXT_PUBLIC_FIREBASE_APP_ID || "",
};

const swContent = `// Generated by scripts/inject-firebase-sw.js - do not edit manually
importScripts("https://www.gstatic.com/firebasejs/11.0.2/firebase-app-compat.js");
importScripts("https://www.gstatic.com/firebasejs/11.0.2/firebase-messaging-compat.js");

firebase.initializeApp(${JSON.stringify(config)});

const messaging = firebase.messaging();

messaging.onBackgroundMessage(function (payload) {
  const title = payload?.notification?.title || payload?.data?.title || "Tijaar";
  const options = {
    body: payload?.notification?.body || payload?.data?.body || "",
    icon: "/vite.svg",
    data: payload?.data || {},
  };
  self.registration.showNotification(title, options);
});

self.addEventListener("notificationclick", function (event) {
  event.notification.close();
  const data = event.notification.data || {};
  const url = data.deep_link || data.url || "/";
  const fullUrl = url.startsWith("http") ? url : self.location.origin + (url.startsWith("/") ? url : "/" + url);
  event.waitUntil(clients.matchAll({ type: "window", includeUncontrolled: true }).then(function (clientList) {
    for (var i = 0; i < clientList.length; i++) {
      if (clientList[i].url && "focus" in clientList[i]) {
        clientList[i].navigate(fullUrl);
        return clientList[i].focus();
      }
    }
    if (clients.openWindow) return clients.openWindow(fullUrl);
  }));
});
`;

const outPath = join(root, "public", "firebase-messaging-sw.js");
writeFileSync(outPath, swContent, "utf8");
console.log("Wrote", outPath);
